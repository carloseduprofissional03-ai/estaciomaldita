/*
 * Código do Apps Script que dá vida ao mapa de alerta usando uma planilha do
 * Google Sheets (gratuito). Este texto é mostrado na Área da equipe, na aba
 * "Mapa de alerta", para ser copiado e colado em Extensões > Apps Script.
 * (Escrito sem crase e sem interpolação para poder ser copiado como está.)
 */
export const APPS_SCRIPT_CODE = [
  "/**",
  " * MAPA DE ALERTA - Da Nascente a Foz",
  " *",
  " * Como usar:",
  " * 1. Crie uma planilha no Google Sheets com o nome que quiser.",
  " * 2. Menu Extensoes > Apps Script e apague o conteudo do arquivo.",
  " * 3. Cole este codigo inteiro e salve.",
  " * 4. Rode a funcao 'configurar' uma vez (autorize o acesso).",
  " * 5. Implantar > Nova implantacao > Tipo: App da Web",
  " *    - Executar como: Eu",
  " *    - Quem tem acesso: Qualquer pessoa",
  " * 6. Copie a URL que termina em /exec e envie para a equipe do site.",
  " *",
  " * A aba 'Alertas' e o painel de moderacao: mude a coluna 'status' para",
  " * 'oculto' (ou apague a linha) para tirar um aviso do mapa. Alertas com mais",
  " * de 60 dias sao apagados automaticamente todo dia as 3h da manha.",
  " */",
  "",
  "var ABA = 'Alertas';",
  "var VALIDADE_DIAS = 60;",
  "",
  "function configurar() {",
  "  var sheet = aba();",
  "  if (sheet.getLastRow() === 0) {",
  "    sheet.appendRow(['id', 'criado_em', 'titulo', 'descricao', 'categoria', 'lat', 'lng', 'referencia', 'contato', 'status']);",
  "  }",
  "  var triggers = ScriptApp.getProjectTriggers();",
  "  for (var i = 0; i < triggers.length; i++) {",
  "    if (triggers[i].getHandlerFunction() === 'limparAlertasAntigos') {",
  "      ScriptApp.deleteTrigger(triggers[i]);",
  "    }",
  "  }",
  "  ScriptApp.newTrigger('limparAlertasAntigos').timeBased().everyDays(1).atHour(3).create();",
  "  return 'Pronto: aba criada e limpeza diaria agendada.';",
  "}",
  "",
  "function doGet() {",
  "  return json({ ok: true, alertas: lerAlertas() });",
  "}",
  "",
  "function doPost(e) {",
  "  try {",
  "    var p = (e && e.parameter) ? e.parameter : {};",
  "    if (!p.titulo || !p.lat || !p.lng) {",
  "      return json({ ok: false, erro: 'Faltam dados: titulo, lat e lng sao obrigatorios.' });",
  "    }",
  "    var sheet = aba();",
  "    sheet.appendRow([",
  "      Utilities.getUuid(),",
  "      new Date(),",
  "      limpar(p.titulo, 120),",
  "      limpar(p.descricao, 600),",
  "      limpar(p.categoria, 40),",
  "      Number(p.lat),",
  "      Number(p.lng),",
  "      limpar(p.referencia, 160),",
  "      limpar(p.contato, 120),",
  "      'aprovado'",
  "    ]);",
  "    return json({ ok: true });",
  "  } catch (err) {",
  "    return json({ ok: false, erro: String(err) });",
  "  }",
  "}",
  "",
  "function lerAlertas() {",
  "  var sheet = aba();",
  "  var valores = sheet.getDataRange().getValues();",
  "  var lista = [];",
  "  for (var i = 1; i < valores.length; i++) {",
  "    var l = valores[i];",
  "    if (String(l[9]).toLowerCase() !== 'aprovado') continue;",
  "    if (!l[2]) continue;",
  "    lista.push({",
  "      id: String(l[0]),",
  "      criadoEm: new Date(l[1]).toISOString(),",
  "      titulo: String(l[2]),",
  "      descricao: String(l[3] || ''),",
  "      categoria: String(l[4] || 'outro'),",
  "      lat: Number(l[5]),",
  "      lng: Number(l[6]),",
  "      referencia: String(l[7] || ''),",
  "      contato: l[8] ? String(l[8]) : ''",
  "    });",
  "  }",
  "  return lista;",
  "}",
  "",
  "function limparAlertasAntigos() {",
  "  var sheet = aba();",
  "  var limite = new Date().getTime() - VALIDADE_DIAS * 24 * 60 * 60 * 1000;",
  "  var valores = sheet.getDataRange().getValues();",
  "  for (var i = valores.length - 1; i >= 1; i--) {",
  "    var quando = new Date(valores[i][1]).getTime();",
  "    if (quando && quando < limite) sheet.deleteRow(i + 1);",
  "  }",
  "}",
  "",
  "function aba() {",
  "  var ss = SpreadsheetApp.getActiveSpreadsheet();",
  "  var sheet = ss.getSheetByName(ABA);",
  "  if (!sheet) sheet = ss.insertSheet(ABA);",
  "  return sheet;",
  "}",
  "",
  "function limpar(v, max) {",
  "  return String(v == null ? '' : v).replace(/\\s+/g, ' ').trim().slice(0, max);",
  "}",
  "",
  "function json(obj) {",
  "  return ContentService.createTextOutput(JSON.stringify(obj)).setMimeType(ContentService.MimeType.JSON);",
  "}",
].join("\n");
