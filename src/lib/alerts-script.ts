/*
 * Código do Apps Script que dá vida à planilha do Google (gratuita) usada pelo
 * mapa de alerta e pela área "A Ilha" (avisos e instituições/ONGs).
 * Este texto é mostrado na Área da equipe, para ser copiado e colado em
 * Extensões > Apps Script. (Sem crase e sem interpolação, para copiar como está.)
 */
export const APPS_SCRIPT_CODE = [
  "/**",
  " * PLANILHA DA COMUNIDADE - Da Nascente a Foz",
  " *",
  " * Serve o mapa de alerta e a area 'A Ilha' (avisos e instituicoes/ONGs).",
  " *",
  " * Como usar:",
  " * 1. Crie uma planilha no Google Sheets com o nome que quiser.",
  " * 2. Menu Extensoes > Apps Script e apague o conteudo do arquivo.",
  " * 3. Cole este codigo inteiro e salve.",
  " * 4. Rode a funcao 'configurar' uma vez (autorize o acesso).",
  " * 5. Implantar > Nova implantacao > Tipo: App da Web",
  " *    - Executar como: Eu",
  " *    - Quem tem acesso: Qualquer pessoa",
  " * 6. Copie a URL que termina em /exec e envie para a equipe do site.",
  " *",
  " * Moderacao: cada aba tem a coluna 'status'. Mude para 'oculto' (ou apague a",
  " * linha) para tirar um item do site. Alertas com mais de 60 dias e avisos",
  " * vencidos ha mais de 30 dias sao apagados automaticamente todo dia as 3h.",
  " */",
  "",
  "var RECURSOS = {",
  "  alertas: {",
  "    aba: 'Alertas',",
  "    colunas: ['id', 'criado_em', 'titulo', 'descricao', 'categoria', 'lat', 'lng', 'referencia', 'contato', 'status']",
  "  },",
  "  avisos: {",
  "    aba: 'Avisos',",
  "    colunas: ['id', 'criado_em', 'titulo', 'texto', 'publicado_por', 'contato', 'ate', 'status']",
  "  },",
  "  instituicoes: {",
  "    aba: 'Instituicoes',",
  "    colunas: ['id', 'criado_em', 'nome', 'tipo', 'descricao', 'publico', 'referencia', 'horarios', 'contato', 'como_ajudar', 'status']",
  "  }",
  "};",
  "",
  "var VALIDADE_ALERTA_DIAS = 60;",
  "var VALIDADE_AVISO_DIAS = 30;",
  "",
  "function configurar() {",
  "  for (var chave in RECURSOS) {",
  "    var sheet = abaDo(chave);",
  "    if (sheet.getLastRow() === 0) {",
  "      sheet.appendRow(RECURSOS[chave].colunas);",
  "      sheet.setFrozenRows(1);",
  "    }",
  "  }",
  "  var triggers = ScriptApp.getProjectTriggers();",
  "  for (var i = 0; i < triggers.length; i++) {",
  "    if (triggers[i].getHandlerFunction() === 'limparAntigos') {",
  "      ScriptApp.deleteTrigger(triggers[i]);",
  "    }",
  "  }",
  "  ScriptApp.newTrigger('limparAntigos').timeBased().everyDays(1).atHour(3).create();",
  "  return 'Pronto: abas criadas e limpeza diaria agendada.';",
  "}",
  "",
  "function doGet(e) {",
  "  var recurso = (e && e.parameter && e.parameter.recurso) ? e.parameter.recurso : 'alertas';",
  "  if (!RECURSOS[recurso]) return json({ ok: false, erro: 'Recurso desconhecido: ' + recurso });",
  "  return json({ ok: true, recurso: recurso, itens: lerItens(recurso) });",
  "}",
  "",
  "function doPost(e) {",
  "  try {",
  "    var p = (e && e.parameter) ? e.parameter : {};",
  "    var recurso = p.recurso ? p.recurso : 'alertas';",
  "    if (!RECURSOS[recurso]) {",
  "      return json({ ok: false, erro: 'Recurso desconhecido: ' + recurso });",
  "    }",
  "    var sheet = abaDo(recurso);",
  "    var colunas = RECURSOS[recurso].colunas;",
  "    var linha = [];",
  "    for (var i = 0; i < colunas.length; i++) {",
  "      linha.push(valorDaColuna(colunas[i], p));",
  "    }",
  "    sheet.appendRow(linha);",
  "    return json({ ok: true });",
  "  } catch (err) {",
  "    return json({ ok: false, erro: String(err) });",
  "  }",
  "}",
  "",
  "function valorDaColuna(coluna, p) {",
  "  if (coluna === 'id') return Utilities.getUuid();",
  "  if (coluna === 'criado_em') return new Date();",
  "  if (coluna === 'status') return 'aprovado';",
  "  if (coluna === 'lat' || coluna === 'lng') return Number(p[coluna]);",
  "  if (coluna === 'ate') return p.ate ? new Date(p.ate) : '';",
  "  return limpar(p[coluna], coluna === 'descricao' || coluna === 'texto' ? 900 : 170);",
  "}",
  "",
  "function lerItens(recurso) {",
  "  var sheet = abaDo(recurso);",
  "  var colunas = RECURSOS[recurso].colunas;",
  "  var valores = sheet.getDataRange().getValues();",
  "  var lista = [];",
  "  for (var i = 1; i < valores.length; i++) {",
  "    var linha = valores[i];",
  "    var item = {};",
  "    var vazio = true;",
  "    for (var j = 0; j < colunas.length; j++) {",
  "      var v = linha[j];",
  "      if (colunas[j] === 'criado_em' || colunas[j] === 'ate') {",
  "        item[colunas[j]] = v ? new Date(v).toISOString() : '';",
  "      } else {",
  "        item[colunas[j]] = v;",
  "      }",
  "      if (String(v) !== '') vazio = false;",
  "    }",
  "    if (vazio) continue;",
  "    if (String(item.status).toLowerCase() !== 'aprovado') continue;",
  "    if (!item.id) item.id = 'linha_' + (i + 1);",
  "    lista.push(item);",
  "  }",
  "  return lista;",
  "}",
  "",
  "function limparAntigos() {",
  "  limparPorIdade('alertas', 'criado_em', VALIDADE_ALERTA_DIAS);",
  "  limparAvisosVencidos();",
  "}",
  "",
  "function limparPorIdade(recurso, coluna, dias) {",
  "  var sheet = abaDo(recurso);",
  "  var colunas = RECURSOS[recurso].colunas;",
  "  var posicao = colunas.indexOf(coluna) + 1;",
  "  if (posicao < 1) return;",
  "  var limite = new Date().getTime() - dias * 24 * 60 * 60 * 1000;",
  "  var valores = sheet.getDataRange().getValues();",
  "  for (var i = valores.length - 1; i >= 1; i--) {",
  "    var quando = new Date(valores[i][posicao - 1]).getTime();",
  "    if (quando && quando < limite) sheet.deleteRow(i + 1);",
  "  }",
  "}",
  "",
  "function limparAvisosVencidos() {",
  "  var sheet = abaDo('avisos');",
  "  var colunas = RECURSOS.avisos.colunas;",
  "  var posicaoAte = colunas.indexOf('ate') + 1;",
  "  var posicaoCriado = colunas.indexOf('criado_em') + 1;",
  "  var limite = new Date().getTime() - VALIDADE_AVISO_DIAS * 24 * 60 * 60 * 1000;",
  "  var valores = sheet.getDataRange().getValues();",
  "  for (var i = valores.length - 1; i >= 1; i--) {",
  "    var ate = valores[i][posicaoAte - 1];",
  "    var referencia = ate ? new Date(ate).getTime() : new Date(valores[i][posicaoCriado - 1]).getTime();",
  "    if (referencia && referencia < limite) sheet.deleteRow(i + 1);",
  "  }",
  "}",
  "",
  "function abaDo(recurso) {",
  "  var ss = SpreadsheetApp.getActiveSpreadsheet();",
  "  var nome = RECURSOS[recurso].aba;",
  "  var sheet = ss.getSheetByName(nome);",
  "  if (!sheet) sheet = ss.insertSheet(nome);",
  "  return sheet;",
  "}",
  "",
  "function limpar(v, max) {",
  "  return String(v == null ? '' : v).replace(/\\s+/g, ' ').trim().slice(0, max);",
  "}",
  "",
  "function json(obj) {",
  "  return ContentService.createTextOutput(JSON.stringify(obj)).setMimeType(ContentService.MimeType.JSON);",
  "}",
].join("\n");
